#!/usr/bin/env python3
"""gen 脚本共享骨架（#178 刀1）。

只抽 gen-tags.py 真正需要的公共件，别过度设计：
  - input_root(): 输入寻径（assets/minecraft 优先、回退 MCV_REF_SRC
    指向的本机解包树，仿 gen-blocks.py 先例；本机路径绝不写死入仓）。
  - file_header(): 产物头注模板（GENERATED by … — do not edit + 数据源版本）。
  - drift_guard(): 输出计数摘要，供交卷/对拍独立计数核对。
"""

import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
# 本机解包参考树根（含 assets/minecraft 与 data/minecraft/**），仅经环境
# 变量注入——本机路径绝不写死入仓（同 gen-blocks.py）。
REF_SRC = Path(os.environ["MCV_REF_SRC"]) if os.environ.get("MCV_REF_SRC") else None
VANILLA = ROOT / "assets" / "minecraft"

# 数据源版本标识（写入产物头注）。
DATA_VERSION = "vanilla-26.1"


def input_root(must_contain: str) -> Path:
    """寻径数据根：仓库内 assets/minecraft 优先，缺失时回退 MCV_REF_SRC。

    must_contain：相对数据根的必需子路径（如 "data/minecraft/tags"），
    不存在则直接 sys.exit 给出修复指引（同 gen-blocks.py 的缺树报错）。
    回退候选含 REF_SRC/assets/minecraft（素材）与 REF_SRC 根（26.1 解包树
    的 data/ 挂在根下）。
    """
    cands = [VANILLA]
    if REF_SRC:
        cands += [REF_SRC / "assets" / "minecraft", REF_SRC]
    for cand in cands:
        if cand is not None and (cand / must_contain).is_dir():
            return cand
    hint = "置 MCV_REF_SRC=<26.1解包树根> 或就位 " + str(VANILLA)
    sys.exit(f"缺 {must_contain} 树：{hint}")


def file_header(script: str, extra: list[str]) -> str:
    """产物头注：GENERATED 标记 + 数据源版本 + 额外说明行。"""
    lines = [
        f"// GENERATED by ci/{script} — do not edit.",
        f"// 数据源: {DATA_VERSION}（同 assets/ 素材政策，DEVELOP_ONLY：",
        "//   只含 tag 名/方块名短标识符与数字 id，不含原版 JSON 原文）。",
    ]
    lines += [f"// {ln}" for ln in extra]
    return "\n".join(lines) + "\n"


def drift_guard(counts: dict[str, int]) -> None:
    """打印计数摘要（stdout），供本地跑脚本时与独立计数（jq/wc）两路对照。"""
    for k, v in sorted(counts.items()):
        print(f"count[{k}] = {v}")
